# Вода: норма и учёт выпитого. Запуск: python3 tests/water_check.py index.html [папка_скриншотов]
import asyncio,json,os,sys,shutil,tempfile,http.server,threading,functools
from playwright.async_api import async_playwright
HTML=os.path.abspath(sys.argv[1]);SHOT=sys.argv[2] if len(sys.argv)>2 else None
tmp=tempfile.mkdtemp();shutil.copy(HTML,tmp+'/index.html')
if os.path.isdir(os.path.dirname(HTML)+'/media'):os.symlink(os.path.dirname(HTML)+'/media',tmp+'/media')
srv=http.server.ThreadingHTTPServer(('127.0.0.1',0),functools.partial(type('Q',(http.server.SimpleHTTPRequestHandler,),{'log_message':lambda *a:None}),directory=tmp))
threading.Thread(target=srv.serve_forever,daemon=True).start();URL=f'http://127.0.0.1:{srv.server_address[1]}/index.html'
R=[]
def ok(n,c,x=''):R.append(bool(c));print(('PASS ' if c else 'FAIL ')+n+(' · '+str(x) if x!='' else ''))
async def m():
  async with async_playwright() as p:
    b=await p.chromium.launch();pg=await b.new_page(viewport={'width':390,'height':844},device_scale_factor=2);errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    await pg.goto(URL);await pg.wait_for_timeout(300)
    await pg.evaluate("localStorage.setItem('gym45_nutrition_target_v1',JSON.stringify({sex:'male',goal:'maintain',activity:'light',age:45,weight:96,height:180,bf:20,src:{units:'metric',w:'96',h:'180'},updatedAt:1}))");await pg.reload();await pg.wait_for_timeout(300)
    await pg.evaluate("el('login').style.display='none';renderFood();show('food')");await pg.wait_for_timeout(100)
    n=json.loads(await pg.evaluate("JSON.stringify(wtNorm())"))
    ok('норма: 35 мл × 96 кг = 3,35 л (14 стаканов)',n['ml']==3350 and n['glasses']==14,(n['ml'],n['glasses']))
    ok('карточка «Вода» в дневнике, по умолчанию ввод стаканами',await pg.evaluate("!!el('wtCard')&&wtSt().mode==='glass'&&el('wtVis').querySelectorAll('i').length===14"))
    for i in range(4):await pg.click('#wtRing')
    r=await pg.evaluate("[wtDrunk(),el('wtPct').textContent,el('wtSub').textContent,el('wtVis').querySelectorAll('i.on').length,el('wtNote').textContent]")
    ok('4 нажатия на круг = 4 стакана = 1 л, итог в литрах',r[0]==1000 and r[1]=='30%' and r[2]=='1 л из 3,35 л' and r[3]==4,r)
    ok('подпись: выпито стаканов и сколько осталось',r[4].startswith('Выпито 4 ст.') and 'осталось 2,35 л' in r[4],r[4])
    if SHOT:await pg.evaluate("el('wtCard').scrollIntoView()");await pg.screenshot(path=SHOT+'/water-glass.png')
    await pg.evaluate("document.querySelector('#wtMode [data-v=\"ml\"]').click()");await pg.wait_for_timeout(60)
    ok('режим «Миллилитры»: бутылка и кнопки 100/250/500/1000 мл',await pg.evaluate("!!el('wtVis').querySelector('.wt-bottle')&&[...el('wtAdd').querySelectorAll('.wt-chip')].map(b=>b.dataset.ml).join()==='100,250,500,1000,250'"))
    await pg.evaluate("[...el('wtAdd').querySelectorAll('.wt-chip')].find(b=>b.dataset.ml==='500'&&!b.dataset.k).click()")
    await pg.click('#wtVis')
    ok('+500 мл, затем нажатие на бутылку добавляет выбранные 500 мл',await pg.evaluate("wtDrunk()")==2000)
    await pg.evaluate("el('wtAdd').querySelector('[data-k=\"tea\"]').click()")
    ok('чай/кофе 250 мл засчитан как 200 мл',await pg.evaluate("wtDrunk()")==2200)
    await pg.click('#wtUndo');ok('«Отменить» убирает последнюю запись',await pg.evaluate("wtDrunk()")==2000)
    ok('итог в литрах и в режиме мл',await pg.evaluate("el('wtSub').textContent")=='2 л из 3,35 л')
    if SHOT:await pg.screenshot(path=SHOT+'/water-ml.png')
    await pg.click('#wtHeat');ok('жара: норма +500 мл',await pg.evaluate("wtNorm().ml")==3850)
    await pg.evaluate("ntTab('norm')");await pg.wait_for_timeout(80)
    ok('«Норма»: блок «Вода» с расшифровкой',await pg.evaluate("el('ntNormOut').innerText.includes('Вода: 3,85 л в день')&&el('ntNormOut').innerText.includes('35 мл × 96 кг')"))
    if SHOT:await pg.evaluate("document.querySelector('.wt-normnote').scrollIntoView()");await pg.screenshot(path=SHOT+'/water-norm.png')
    big=await pg.evaluate("(()=>{const t=ntT();localStorage.setItem('gym45_nutrition_target_v1',JSON.stringify(Object.assign({},t,{weight:110,bf:0})));const x=wtNorm();localStorage.setItem('gym45_nutrition_target_v1',JSON.stringify(t));return x})()")
    ok('лишний вес (110 кг, 180 см): от идеального веса 80 кг',big['ml']==2800+500,big['ml'])
    await pg.evaluate("safe.set(safe.get().concat([{date:localDate(),name:'GVT',vol:1000}]))")
    ok('день тренировки: +500 мл',await pg.evaluate("wtNorm().ml")==4350)
    ok('без горизонтальной прокрутки',await pg.evaluate("document.documentElement.scrollWidth<=innerWidth+1"))
    await pg.reload();await pg.wait_for_timeout(300)
    ok('после перезапуска выпитое и режим на месте',await pg.evaluate("wtDrunk()===2000&&wtSt().mode==='ml'&&wtSt().heat===true"))
    ok('ошибок JS нет',not errs,errs[:3])
    await b.close()
  print(f'\n{sum(R)}/{len(R)} PASS');sys.exit(0 if all(R) else 1)
asyncio.run(m())
